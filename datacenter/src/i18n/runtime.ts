const interpolate = (template, params = {}) =>
  String(template).replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? ''))

export const normalizeDatacenterLocale = (locale) => {
  const normalized = String(locale || '')
    .trim()
    .toLowerCase()
  return normalized.startsWith('en') ? 'en' : 'zh'
}

const getInitialLocale = () => {
  if (typeof globalThis.localStorage === 'undefined') {
    return 'zh'
  }
  try {
    return normalizeDatacenterLocale(Storage.getLanguage())
  } catch {
    return 'zh'
  }
}

export const datacenterLocale = ref(getInitialLocale())

export const elementPlusLocale = computed(() =>
  datacenterLocale.value === 'en' ? enLocale : zhCnLocale,
)

export const createDatacenterTranslator = (localeRef = datacenterLocale) => {
  return (key, params = {}) => {
    const locale = normalizeDatacenterLocale(localeRef.value)
    const segments = String(key).split('.')
    let value = datacenterMessages[locale]

    for (const segment of segments) {
      value = value?.[segment]
    }

    if (typeof value !== 'string') {
      return key
    }

    return interpolate(value, params)
  }
}

export const t = createDatacenterTranslator()

export const setDatacenterLocale = (locale) => {
  const normalized = normalizeDatacenterLocale(locale)
  datacenterLocale.value = normalized
  if (typeof globalThis.localStorage === 'undefined') {
    return normalized
  }
  try {
    Storage.setLanguage(normalized)
  } catch {
    // Node 测试环境没有 localStorage，这里只更新响应式 locale。
  }
  return normalized
}

export const getDatacenterRouteTitle = (routeName) => {
  if (routeName === 'datacenter-debug') {
    return t('route.datacenterDebug')
  }
  return t('route.datacenter')
}
